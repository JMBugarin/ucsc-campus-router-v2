// Lists the weak spots of the walking network for checking on foot, in docs/walking-network-audit.md:
// doors far from any mapped path, edges OpenStreetMap no longer has, and paths that stop just short of a door.
// Run after npm run data: npm run network:audit
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { metres } from './rooms.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..', '..')
const graph = JSON.parse(readFileSync(join(here, '..', 'public', 'data', 'graph.json'), 'utf8'))
const places = JSON.parse(readFileSync(join(here, '..', 'public', 'data', 'places.json'), 'utf8')).places
const shapes = JSON.parse(readFileSync(join(root, 'graph', 'ucsc', 'shapes.json'), 'utf8'))
const SITE = 'https://jmbugarin.github.io/ucsc-campus-router-v2/'
const FAR_M = 25

const n = graph.lat.length
const shape = new Map()
for (let i = 0; i < graph.shapes.pairs.length / 2; i++) {
  const pts = []
  for (let k = graph.shapes.off[i]; k < graph.shapes.off[i + 1]; k++) pts.push([graph.shapes.pts[2 * k], graph.shapes.pts[2 * k + 1]])
  shape.set(graph.shapes.pairs[2 * i] * n + graph.shapes.pairs[2 * i + 1], pts)
}
const degree = new Array(n).fill(0)
const pairs = []
for (let i = 0; i < graph.edges.length; i += 4) {
  const a = graph.edges[i]
  const b = graph.edges[i + 1]
  degree[a]++
  if (a < b) pairs.push([a, b])
}
const line = (a, b) => [[graph.lat[a], graph.lon[a]], ...(shape.get(a * n + b) ?? []), [graph.lat[b], graph.lon[b]]]

function nearestPath(lat, lon) {
  const kx = Math.cos((lat * Math.PI) / 180) * 111320
  const ky = 110540
  let best = Infinity
  for (const [a, b] of pairs) {
    const pts = line(a, b)
    for (let i = 1; i < pts.length; i++) {
      const ax = (pts[i - 1][1] - lon) * kx, ay = (pts[i - 1][0] - lat) * ky
      const bx = (pts[i][1] - lon) * kx, by = (pts[i][0] - lat) * ky
      const dx = bx - ax, dy = by - ay, l2 = dx * dx + dy * dy
      const u = l2 ? Math.max(0, Math.min(1, -(ax * dx + ay * dy) / l2)) : 0
      best = Math.min(best, Math.hypot(ax + u * dx, ay + u * dy))
    }
  }
  return best
}

const farDoors = []
for (const p of places) {
  if (p.kind === 'room' || !p.entrances?.length) continue
  p.entrances.forEach(([lat, lon], i) => {
    const d = nearestPath(lat, lon)
    if (d > FAR_M) farDoors.push({ p, i, lat, lon, d })
  })
}
farDoors.sort((x, y) => y.d - x.d)
const roomsAffected = places.filter((r) => r.kind === 'room' && r.entrances?.every(([la, lo]) => nearestPath(la, lo) > FAR_M))
const deadEnds = []
for (let v = 0; v < n; v++) {
  if (degree[v] !== 1) continue
  // a footpath that ends at a door is right; one that stops a few metres short may have lost its last stretch
  const at = [graph.lat[v], graph.lon[v]]
  const doors = places.filter((p) => p.kind !== 'room').flatMap((p) => (p.entrances ?? []).map((e) => ({ p, d: metres(e, at) })))
  const closest = Math.min(...doors.map((x) => x.d))
  if (closest > 4 && closest < 20) deadEnds.push({ v, gap: closest, near: [...new Set(doors.filter((x) => x.d < 20).map((x) => x.p.name))] })
}
const osm = (lat, lon) => `https://www.openstreetmap.org/?mlat=${lat}&mlon=${lon}#map=19/${lat}/${lon}`
const lines = [
  '# Walking network audit',
  '',
  'Weak spots in the walking network behind directions, generated by `web/scripts/network-audit.mjs` (`npm run network:audit` in `web/`). Walk each one; fix what is wrong in OpenStreetMap (or in `data/rooms.json` for a room\'s door), then rebuild the graph data.',
  '',
  `## Doors more than ${FAR_M} m from any mapped path (${farDoors.length})`,
  '',
  'The route reaches these doors by a straight, dotted "approximate" line. A missing footpath in OpenStreetMap, or a door pinned in the wrong place, is the usual cause.',
  '',
  '| Place | Door | Nearest path | Check |',
  '|---|---|---|---|',
  ...farDoors.map((f) => `| [${f.p.name}](${SITE}#/p/${f.p.id}) | ${f.i + 1} of ${f.p.entrances.length} | ${Math.round(f.d)} m | [OSM](${osm(f.lat, f.lon)}) |`),
  '',
  `Rooms whose every routed door is that far: ${roomsAffected.length ? roomsAffected.map((r) => r.name).join(', ') : 'none'}.`,
  '',
  `## Edges OpenStreetMap no longer has (${shapes.unmatched.length})`,
  '',
  'The graph was downloaded before these paths changed in OpenStreetMap, so they are drawn straight. Check whether the path is still there.',
  '',
  ...shapes.unmatched.map((u) => `- nodes ${u.from} to ${u.to}, ${u.length_m} m: from [${graph.lat[u.from]}, ${graph.lon[u.from]}](${osm(graph.lat[u.from], graph.lon[u.from])}) to [${graph.lat[u.to]}, ${graph.lon[u.to]}](${osm(graph.lat[u.to], graph.lon[u.to])})`),
  '',
  `## Paths that stop 4 to 20 m short of a door (${deadEnds.length})`,
  '',
  'A path that stops just short of a door may really continue to it, or to another path. Worth a look on the way past.',
  '',
  ...deadEnds.sort((x, y) => y.gap - x.gap).map((d) => `- ${Math.round(d.gap)} m short: [${graph.lat[d.v]}, ${graph.lon[d.v]}](${osm(graph.lat[d.v], graph.lon[d.v])}) near ${d.near.join(', ')}`),
  '',
]
writeFileSync(join(root, 'docs', 'walking-network-audit.md'), lines.join('\n'))
console.log(`network audit: ${farDoors.length} far doors, ${shapes.unmatched.length} changed edges, ${deadEnds.length} paths stopping short of a door`)
